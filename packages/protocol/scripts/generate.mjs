#!/usr/bin/env node
// Generate src/generated/{solana.ts,abi.ts} from the frozen interface artifacts:
//   interfaces/solana/xmr_swap.idl.json   -> TypeScript interfaces and Borsh codecs for every
//                                            account, type, event and instruction
//   interfaces/ethereum/IXmrSwap.abi.json -> the ABI `as const` (viem infers types from it)
// The output is committed; `--check` fails if it is stale (run by the tests).
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../../..');
const idl = JSON.parse(readFileSync(path.join(repo, 'interfaces/solana/xmr_swap.idl.json'), 'utf8'));
const abi = JSON.parse(readFileSync(path.join(repo, 'interfaces/ethereum/IXmrSwap.abi.json'), 'utf8'));

const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascal = (s) => camel(s).replace(/^./, (c) => c.toUpperCase());
const SCALARS = {
  u8: ['number', 'u8'], u16: ['number', 'u16'], u32: ['number', 'u32'],
  u64: ['bigint', 'u64'], i64: ['bigint', 'i64'], u128: ['bigint', 'u128'],
  bool: ['boolean', 'bool'], pubkey: ['string', 'pubkey'], string: ['string', 'string'], bytes: ['Uint8Array', 'bytes'],
};
/** IDL type -> [TypeScript type, codec expression]. */
function map(t) {
  if (typeof t === 'string') {
    if (!SCALARS[t]) throw new Error(`unsupported IDL type ${t}`);
    return SCALARS[t];
  }
  if (t.array) {
    const [item, n] = t.array;
    if (item === 'u8') return ['Uint8Array', `fixedBytes(${n})`];
    const [ts, codec] = map(item);
    return [`${/[ |]/.test(ts) ? `(${ts})` : ts}[]`, `array(${codec}, ${n})`];
  }
  if (t.vec) {
    const [ts, codec] = map(t.vec);
    return [`${/[ |]/.test(ts) ? `(${ts})` : ts}[]`, `vec(${codec})`];
  }
  if (t.option) {
    const [ts, codec] = map(t.option);
    return [`${ts} | null`, `option(${codec})`];
  }
  if (t.defined) return [t.defined.name, `${t.defined.name}Codec`];
  throw new Error(`unsupported IDL type ${JSON.stringify(t)}`);
}
const doc = (docs, indent = '') => (docs?.length ? `${indent}/** ${docs.join(' ').replace(/\*\//g, '* /')} */\n` : '');

// Emit structs in dependency order.
const types = new Map(idl.types.map((t) => [t.name, t]));
const emitted = new Set();
let out = `// GENERATED by scripts/generate.mjs from interfaces/solana/xmr_swap.idl.json. Do not edit.
/* eslint-disable */
import { type Codec, type StructCodec, array, bool, bytes, fixedBytes, i64, option, pubkey, string, struct, u128, u16, u32, u64, u8, vec } from '../borsh.js';

`;
function deps(t) {
  if (typeof t === 'string') return [];
  if (t.array) return deps(t.array[0]);
  if (t.vec) return deps(t.vec);
  if (t.option) return deps(t.option);
  if (t.defined) return [t.defined.name];
  return [];
}
function emitType(name) {
  if (emitted.has(name)) return;
  emitted.add(name);
  const t = types.get(name);
  if (!t) throw new Error(`IDL type ${name} not found`);
  if (t.type.kind !== 'struct') throw new Error(`${name}: only structs are supported`);
  const fields = t.type.fields ?? [];
  for (const f of fields) for (const d of deps(f.type)) emitType(d);
  out += doc(t.docs);
  out += `export interface ${name} {\n`;
  for (const f of fields) out += `${doc(f.docs, '  ')}  ${camel(f.name)}: ${map(f.type)[0]};\n`;
  out += `}\n`;
  out += `export const ${name}Codec: StructCodec<${name}> = struct<${name}>('${name}', [\n`;
  for (const f of fields) out += `  ['${camel(f.name)}', '${f.name}', ${map(f.type)[1]}],\n`;
  out += `]);\n\n`;
}
for (const t of idl.types) emitType(t.name);

const disc = (d) => `Uint8Array.of(${d.join(', ')})`;

out += `// ------------------------------------------------------------------ accounts\n\n`;
out += `export const ACCOUNTS = {\n`;
for (const a of idl.accounts) out += `  ${a.name}: { discriminator: ${disc(a.discriminator)}, codec: ${a.name}Codec },\n`;
out += `} as const;\nexport type AccountName = keyof typeof ACCOUNTS;\n`;
out += `export interface AccountTypes {\n${idl.accounts.map((a) => `  ${a.name}: ${a.name};`).join('\n')}\n}\n\n`;

out += `// ------------------------------------------------------------------ events\n\n`;
out += `export const EVENTS = {\n`;
for (const e of idl.events) out += `  ${e.name}: { discriminator: ${disc(e.discriminator)}, codec: ${e.name}Codec },\n`;
out += `} as const;\nexport type EventName = keyof typeof EVENTS;\n`;
out += `export interface EventTypes {\n${idl.events.map((e) => `  ${e.name}: ${e.name};`).join('\n')}\n}\n\n`;

out += `// ------------------------------------------------------------------ instructions\n\n`;
out += `export interface AccountMeta {\n  /** IDL account name. */\n  readonly name: string;\n  readonly writable: boolean;\n  readonly signer: boolean;\n  /** An absent optional account is passed as the program id. */\n  readonly optional: boolean;\n}\n\n`;
for (const i of idl.instructions) {
  const name = `${pascal(i.name)}IxArgs`;
  out += doc(i.docs);
  out += `export interface ${name} {\n`;
  for (const a of i.args) out += `  ${camel(a.name)}: ${map(a.type)[0]};\n`;
  out += `}\n`;
  out += `export const ${name}Codec: StructCodec<${name}> = struct<${name}>('${i.name}', [\n`;
  for (const a of i.args) out += `  ['${camel(a.name)}', '${a.name}', ${map(a.type)[1]}],\n`;
  out += `]);\n\n`;
}
out += `export const INSTRUCTIONS = {\n`;
for (const i of idl.instructions) {
  out += `  ${camel(i.name)}: {\n    name: '${i.name}',\n    discriminator: ${disc(i.discriminator)},\n    args: ${pascal(i.name)}IxArgsCodec,\n    accounts: [\n`;
  for (const a of i.accounts) {
    if (a.accounts) throw new Error('composite accounts are not supported');
    out += `      { name: '${a.name}', writable: ${!!a.writable}, signer: ${!!a.signer}, optional: ${!!a.optional} },\n`;
  }
  out += `    ] as readonly AccountMeta[],\n  },\n`;
}
out += `} as const;\nexport type InstructionName = keyof typeof INSTRUCTIONS;\n`;
out += `export interface InstructionArgs {\n${idl.instructions.map((i) => `  ${camel(i.name)}: ${pascal(i.name)}IxArgs;`).join('\n')}\n}\n\n`;

out += `// ------------------------------------------------------------------ errors\n\n`;
out += `/** Anchor error codes are \`6000 + index\` in this order. */\nexport const ERROR_NAMES = [\n${idl.errors.map((e) => `  '${e.name}',`).join('\n')}\n] as const;\n`;
out += `export type ProgramErrorName = (typeof ERROR_NAMES)[number];\nexport const ERROR_CODE_BASE = ${idl.errors[0].code};\n\n`;
out += `/** The development program id frozen in interfaces/solana/program-id.txt. */\nexport const DEV_PROGRAM_ID = '${idl.address}';\n`;

const abiOut = `// GENERATED by scripts/generate.mjs from interfaces/ethereum/IXmrSwap.abi.json. Do not edit.
/* eslint-disable */
/** The frozen ABI of IXmrSwap. Pass it to viem; types are inferred from the \`as const\`. */
export const IXmrSwapAbi = ${JSON.stringify(abi, null, 2)} as const;
`;

const files = { 'src/generated/solana.ts': out, 'src/generated/abi.ts': abiOut };
let stale = false;
for (const [rel, content] of Object.entries(files)) {
  const file = path.resolve(here, '..', rel);
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(file, 'utf8');
    } catch {}
    if (current !== content) {
      console.error(`${rel} is stale: run \`node scripts/generate.mjs\` in packages/protocol`);
      stale = true;
    }
  } else {
    writeFileSync(file, content);
    console.log(`wrote ${rel}`);
  }
}
if (stale) process.exit(1);
