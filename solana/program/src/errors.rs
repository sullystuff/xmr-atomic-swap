//! Error codes are `6000 + index` in this order. The order is frozen in the IDL (SPEC 4.8).
use anchor_lang::prelude::*;

#[error_code]
pub enum SwapError {
    Unauthorized,
    Paused,
    BadState,
    TooEarly,
    TooLate,
    InvalidKeyCommitment,
    InvalidProofOfKnowledge,
    InvalidScalar,
    InvalidEncryptionKey,
    ScalarMismatch,
    OfferDisabled,
    OfferStale,
    SeqTooOld,
    TermsChanged,
    PriceMoved,
    AmountOutOfRange,
    CapacityExceeded,
    NoKeyAvailable,
    KeySlotBusy,
    ApprovalRequired,
    ApprovalInvalid,
    QuoteMismatch,
    QuoteExpired,
    StaleEpoch,
    StaleKeyVersion,
    SignatureInstructionInvalid,
    WrongDirection,
    WrongAsset,
    MintNotAllowed,
    DepositTooHigh,
    ApprovalWindowOutOfRange,
    NoticeWindowOutOfRange,
    ClaimDelayTooShort,
    ClaimWindowTooShort,
    FinalWindowOutOfRange,
    DepthInvalid,
    TiersInvalid,
    TooManyPending,
    SessionBudgetTooLow,
    EvidenceMismatch,
    EvidenceRequired,
    NothingOwed,
    NotClosable,
    VaultNotEmpty,
    MessageTooLarge,
    MessageMalformed,
    OnionInvalid,
    ContactsTooLong,
    ConfigFrozen,
    /// Amount arithmetic at lock only; never reachable in a secret-bearing instruction.
    MathOverflow,
    /// Amendment 1 (SPEC 11.1): the swap's amount is above `max_swap`.
    SwapCapExceeded,
    /// Amendment 1 (SPEC 11.1): the asset's open value would exceed `max_open`.
    OpenCapExceeded,
    /// Amendment 1 (SPEC 11.2): the payout address is the default key, the program or a PDA.
    PayoutInvalid,
    /// Amendment 1 (SPEC 11.6): a watcher is named against `w_z == 0`.
    WatcherNotAllowed,
    /// Amendment 1 (SPEC 11.6): `w_z` is neither 0 nor inside the freeze bounds.
    FreezeWindowOutOfRange,
}
